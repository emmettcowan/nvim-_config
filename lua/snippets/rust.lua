local ls = require("luasnip")
local s = ls.snippet
local t = ls.text_node
local i = ls.insert_node
local rep = require("luasnip.extras").rep
local fmt = require("luasnip.extras.fmt").fmt

return {

  ----------------------------------------------------------------------
  -- Function with doc comment (cursor goes to body first)
  ----------------------------------------------------------------------
  s(
    "fn",
    fmt(
      [[
    /// {}
    fn {}({}){} {{
        {}
    }}
  ]],
      {
        i(1, "Description"),
        i(2, "name"),
        i(3, "params"),
        i(4, " -> ReturnType"),
        i(5, "// code"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Main function
  ----------------------------------------------------------------------
  s(
    "main",
    fmt(
      [[
    fn main() {{
        {}
    }}
  ]],
      { i(1, "// code") }
    )
  ),

  ----------------------------------------------------------------------
  -- Struct
  ----------------------------------------------------------------------
  s(
    "st",
    fmt(
      [[
    /// {}
    struct {} {{
        {}
    }}
  ]],
      {
        i(1, "Struct description"),
        i(2, "Name"),
        i(3, "field: Type"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Enum
  ----------------------------------------------------------------------
  s(
    "en",
    fmt(
      [[
    /// {}
    enum {} {{
        {},
    }}
  ]],
      {
        i(1, "Enum description"),
        i(2, "Name"),
        i(3, "Variant"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Impl block
  ----------------------------------------------------------------------
  s(
    "imp",
    fmt(
      [[
    impl {} {{
        fn {}(&self{}){} {{
            {}
        }}
    }}
  ]],
      {
        i(1, "Type"),
        i(2, "method"),
        i(3, ", param: Type"),
        i(4, " -> ReturnType"),
        i(5, "// code"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Trait
  ----------------------------------------------------------------------
  s(
    "tr",
    fmt(
      [[
    trait {} {{
        fn {}({}){}; 
    }}
  ]],
      {
        i(1, "TraitName"),
        i(2, "method"),
        i(3, "&self"),
        i(4, " -> ReturnType"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Module
  ----------------------------------------------------------------------
  s(
    "mod",
    fmt(
      [[
    mod {} {{
        {}
    }}
  ]],
      {
        i(1, "name"),
        i(2, "// code"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Unit test
  ----------------------------------------------------------------------
  s(
    "test",
    fmt(
      [[
    #[cfg(test)]
    mod tests {{
        use super::*;

        #[test]
        fn {}() {{
            {}
        }}
    }}
  ]],
      {
        i(1, "test_name"),
        i(2, "// assertions"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- match expression
  ----------------------------------------------------------------------
  s(
    "mt",
    fmt(
      [[
    match {} {{
        {} => {},
        _ => {},
    }}
  ]],
      {
        i(1, "value"),
        i(2, "pattern"),
        i(3, "result"),
        i(4, "default"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Result-returning function
  ----------------------------------------------------------------------
  s(
    "res",
    fmt(
      [[
    /// {}
    fn {}({}) -> Result<{}, {}> {{
        {}
    }}
  ]],
      {
        i(1, "Description"),
        i(2, "name"),
        i(3, "params"),
        i(4, "OkType"),
        i(5, "ErrType"),
        i(6, "// code"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Iterator map
  ----------------------------------------------------------------------
  s(
    "map",
    fmt(
      [[
    {}.iter().map(|{}| {{
        {}
    }})
  ]],
      {
        i(1, "items"),
        i(2, "x"),
        i(3, "x"),
      }
    )
  ),

  ----------------------------------------------------------------------
  -- Iterator filter
  ----------------------------------------------------------------------
  s(
    "flt",
    fmt(
      [[
    {}.iter().filter(|{}| {{
        {}
    }})
  ]],
      {
        i(1, "items"),
        i(2, "x"),
        i(3, "x > 0"),
      }
    )
  ),
}
